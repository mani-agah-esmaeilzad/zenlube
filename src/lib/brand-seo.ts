export function buildBrandPageStructuredData(input: {
  brandName: string;
  brandSlug: string;
  description: string;
  productCount: number;
}) {
  const url = `https://www.oilbar.ir/brands/${encodeURIComponent(input.brandSlug)}`;
  const description = input.description.replace(/<[^>]*>/g, " ").replace(/\s+/g, " ").trim();
  return {
    "@context": "https://schema.org",
    "@type": "CollectionPage",
    "@id": `${url}#webpage`,
    url,
    name: `محصولات ${input.brandName}`,
    description: description.length > 170 ? `${description.slice(0, 169)}…` : description,
    inLanguage: "fa-IR",
    isPartOf: { "@id": "https://www.oilbar.ir/#website" },
    about: {
      "@type": "Brand",
      name: input.brandName,
    },
    mainEntity: {
      "@type": "ItemList",
      name: `لیست محصولات ${input.brandName}`,
      numberOfItems: input.productCount,
    },
  };
}

